// Writes apps/mobile/integration_test/parity_data.dart from out/parity.json (first 2 inputs),
// so the on-device test can compare the phone's TFLite output with the reference.
//   node tools/face-model/make_mobile_parity.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const parity = JSON.parse(readFileSync(path.join(here, 'out/parity.json'), 'utf8'));
const n = 2;
const out = path.resolve(here, '../../apps/mobile/integration_test/parity_data.dart');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(
  out,
  `// Generated by tools/face-model/make_mobile_parity.mjs. Do not edit.\n` +
    `const parityInputs = <List<int>>[\n${parity.inputs.slice(0, n).map((i) => `  [${i.join(',')}],`).join('\n')}\n];\n` +
    `const parityDescriptors = <List<double>>[\n${parity.descriptors.slice(0, n).map((d) => `  [${d.join(',')}],`).join('\n')}\n];\n`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
